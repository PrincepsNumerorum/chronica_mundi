#!/usr/bin/env python3
"""src/ruby.tsv = difficult-to-read kanji terms (needs: pip install pykakasi).
A term gets furigana when it is written only in kanji (no katakana / latin) and
 (a) contains a kanji outside the Joyo list (src/joyo.txt), or
 (b) its reading differs from the ordinary reading guessed by pykakasi."""
import glob, os, re, pykakasi
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
JOYO = set(open(os.path.join(SRC, 'joyo.txt'), encoding='utf-8').read().strip())
K = re.compile(r'[㐀-鿿豈-﫿々〆ヶ]')
kk = pykakasi.kakasi()
EA = re.compile(r'中国|朝鮮|韓|東アジア|モンゴル|台湾|ベトナム|満州')
def guess(s): return ''.join(x['hira'] for x in kk.convert(s))
def hira(s): return ''.join(chr(ord(c) - 0x60) if 'ァ' <= c <= 'ヶ' else c for c in s)
def clean(s): return re.sub(r'[・\s＝=ー]', '', s)
READ = {}
for ln in open(os.path.join(SRC, 'joyo_readings.tsv'), encoding='utf-8'):
    c, _, r = ln.rstrip('\n').partition('\t'); READ[c] = set(r.split(','))
VO = str.maketrans('かきくけこさしすせそたちつてとはひふへほ', 'がぎぐげござじずぜぞだぢづでどばびぶべぼ')
PA = str.maketrans('はひふへほ', 'ぱぴぷぺぽ')
def variants(r):
    v = {r, r.translate(VO)[:1] + r[1:], r.translate(PA)[:1] + r[1:]}
    if r[-1:] in 'つくちき': v |= {x[:-1] + 'っ' for x in list(v)}
    return v
def segmentable(w, y):
    """can reading y be split into ordinary readings of each character of w?"""
    from functools import lru_cache
    @lru_cache(None)
    def go(i, j):
        if i == len(w): return j == len(y)
        c = w[i]
        if not K.match(c):
            return y.startswith(c, j) and go(i + 1, j + 1)
        if c == '々' and i:
            cands = READ.get(w[i - 1], set())
        else:
            cands = READ.get(c, set())
        for r in cands:
            for v in variants(r):
                if v and y.startswith(v, j) and go(i + 1, j + len(v)): return True
        return False
    return go(0, 0)
def difficult(w, y, person=False):
    if not K.search(w) or re.search(r'[ァ-ヺA-Za-z0-9０-９（）()「」『』、。]', w): return False
    if any(K.match(c) and c not in JOYO for c in w): return True
    y = clean(y)
    if clean(guess(w)) == y: return False
    if person: return True
    return not segmentable(clean(w), y)
# too familiar to need furigana (kept out even if the rules above flag them)
EXCLUDE = set('''伊藤博文 傭兵 劉備 劉邦 北宋 南宋 北魏 十七条憲法 啓蒙思想 啓蒙専制君主 大飢饉 天智天皇 孟子 宋学 尖閣諸島 小野妹子
尊王攘夷 戊辰戦争 日宋貿易 日独伊三国同盟 李白 杜甫 東晋 楊貴妃 永楽帝 江沢民 琉球 華僑 菩薩 釈迦 藤原鎌足 中臣鎌足 北条時宗
遣隋使 門戸開放 騎士道物語 鞭打ち苦行者 未解読文字 四面楚歌 光武帝 中大兄皇子 北里柴三郎 兵馬俑 蘇我入鹿 坂本龍馬'''.split())
FIX = {'四帝分治制': 'したいぶんちせい'}
out = {}
for path in sorted(glob.glob(os.path.join(SRC, 'terms', '*.txt'))):
    text = open(path, encoding='utf-8').read().replace('\r\n', '\n')
    for chunk in re.split(r'^=== ', text, flags=re.M)[1:]:
        head, _, rest = chunk.partition('\n'); head = head.strip()
        meta = {}
        for ln in rest.split('\n---\n')[0].splitlines():
            if ':' in ln: k, v = ln.split(':', 1); meta[k.strip()] = v.strip()
        y = hira(re.split(r'[（(、,]', meta.get('yomi', ''))[0].strip())
        if not y or not re.fullmatch(r'[ぁ-ゖー・\s]+', y): continue
        if head in EXCLUDE or len(head) < 2: continue
        if difficult(head, y, meta.get('cat', '') == '人物' and EA.search(meta.get('region', ''))): out[head] = y.replace(' ', '')
        for it in meta.get('ruby', '').split(','):
            if '=' in it:
                k, v = it.split('=', 1)
                if k.strip() and v.strip(): out[k.strip()] = hira(v.strip())
out.update({k: v for k, v in FIX.items() if k in out})
with open(os.path.join(SRC, 'ruby.tsv'), 'w', encoding='utf-8') as f:
    f.write('# term\treading  (generated by tools/make_ruby.py; edit freely)\n')
    for k in sorted(out): f.write('%s\t%s\n' % (k, out[k]))
print('ruby terms', len(out))
